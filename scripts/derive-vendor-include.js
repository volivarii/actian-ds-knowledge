#!/usr/bin/env node
"use strict";

// Derives vendor-include.json — the substrate's declaration of its distributable
// top-level surface. Consumers vendor by INCLUSION of exactly these entries, so
// tooling (editor/auth-worker/scripts/tests/contributor-docs) is structurally
// absent from every vendor/ bundle (it's not referenced by the manifest and not
// in the fixed contract set, so it never enters the include-list).
//
// Distributable = { unique first path-segment of every manifest paths/collections
// entry } ∪ { fixed contract files }. Mirrors scripts/llms-txt-generate.js.

var fs = require("node:fs");
var path = require("node:path");

var ROOT = path.resolve(__dirname, "..");

// Root-level contract artifacts that consumers need but that aren't manifest
// `paths` entries (the manifest, the schema dir, the LLM surfaces, the consumer
// docs, and this declaration itself so it travels into vendor/).
var FIXED_CONTRACT = [
  "paths-manifest.json",
  "schemas",
  "clients",
  "llms.txt",
  "llms-full.txt",
  "CONSUMING.md",
  "ARCHITECTURE.md",
  "vendor-include.json",
];

function computeInclude(manifest) {
  var set = new Set(FIXED_CONTRACT);
  var paths = manifest.paths || {};
  for (var k in paths) {
    if (paths[k] && paths[k].path) set.add(paths[k].path.split("/")[0]);
  }
  var collections = manifest.collections || {};
  for (var c in collections) {
    if (collections[c] && collections[c].dir) {
      set.add(collections[c].dir.split("/")[0]);
    }
  }
  return Array.from(set).sort();
}

function generate() {
  var manifest = JSON.parse(
    fs.readFileSync(path.join(ROOT, "paths-manifest.json"), "utf8"),
  );
  return {
    _comment:
      "AUTO-GENERATED by scripts/derive-vendor-include.js. The substrate's distributable top-level surface — consumers vendor ONLY these entries (inclusion, not exclusion), so tooling is structurally absent. Regenerate with `npm run derive:vendor-include`; a drift test in the validate-manifest gate enforces freshness.",
    include: computeInclude(manifest),
  };
}

if (require.main === module) {
  fs.writeFileSync(
    path.join(ROOT, "vendor-include.json"),
    JSON.stringify(generate(), null, 2) + "\n",
  );
  console.log("Generated vendor-include.json");
}

module.exports = { computeInclude: computeInclude, generate: generate };
