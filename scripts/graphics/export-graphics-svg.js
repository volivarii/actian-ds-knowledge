"use strict";

// Extracts SVG for the color-preserving artwork tier (brand illustrations, the
// pyramid mark, partner logos) from Figma, normalizes them, and writes:
//   - components/src/graphics-svg.auto.json          (clean set)
//   - components/dist/graphics/graphics.degraded.json (worklist)
// Returns { exported:[slug], degraded:[{slug,reason}], skipped:Number, wrote:Boolean }.
//
// Unlike the icon exporter, this does NOT sweep a registry category: real Figma
// inspection (docs/superpowers/graphics-slice1-findings.md) found the artwork the
// consumers need lives at specific variant / sub-nodes, not as top-level registry
// components. So the source is an explicit `artworkMap` (`{slug: nodeId}`) passed
// in `opts`, not derived here. That also removes the need to filter junk entries:
// anything not wanted is simply absent from the map.
//
// Thin glue over the tested figma-rest client + normalize-graphics-svg.

const fs = require("node:fs");
const path = require("node:path");
const { normalizeGraphicSvg } = require("./normalize-graphics-svg");

// The curated slice-1 artwork set (docs/superpowers/graphics-slice1-findings.md).
// Later slices extend this map; it stays the CLI's default `artworkMap`, while
// `run(opts)` keeps taking `artworkMap` as a parameter so callers (and tests)
// can inject their own.
const SLICE1_ARTWORK = {
  "illustration-empty-state": "8837:9944",
  "illustration-error-state": "8837:9943",
  "illustration-maintenance": "10932:20528",
  "illustration-success": "10932:21076",
  "actian-pyramid": "7764:7688",
  "zeenea-logo": "12770:6651",
  "actian-data-observability": "7764:7671",
  "loader-logo-adi": "7764:7616",
  "loader-logo-studio": "7973:4948",
  "loader-logo-explorer": "7973:4896",
  "loader-logo-admin": "7973:5050",
};

const AUTO_OUT_PATH = path.join(
  __dirname,
  "..",
  "..",
  "components",
  "src",
  "graphics-svg.auto.json",
);
const DEGRADED_OUT_PATH = path.join(
  __dirname,
  "..",
  "..",
  "components",
  "dist",
  "graphics",
  "graphics.degraded.json",
);

async function run(opts) {
  const fileKey = opts.fileKey;
  const artworkMap = opts.artworkMap || {};
  const rest = opts.rest;
  // Default true: a caller that omits `write` gets the real files (the CLI
  // path). The test passes `write:false` explicitly so it never touches disk.
  const write = opts.write !== false;

  const slugs = Object.keys(artworkMap);
  const idToSlug = {};
  const ids = [];
  for (const slug of slugs) {
    const id = artworkMap[slug];
    idToSlug[id] = slug;
    ids.push(id);
  }

  const cleanArtwork = {};
  const degraded = [];

  if (ids.length > 0) {
    const resp = await rest.getImages(fileKey, ids, { format: "svg" });

    // A Figma API error must NEVER be recorded as artwork loss. Fail loudly
    // instead: a transient error is an error, not a design change.
    const apiErrors = (resp && resp.errors) || [];
    if (apiErrors.length > 0) {
      throw new Error(
        "[graphics] Figma /v1/images returned errors; refusing to treat this as " +
          "artwork loss: " +
          apiErrors
            .map((e) => (e && e.err ? e.err : JSON.stringify(e)))
            .join("; "),
      );
    }

    const images = (resp && resp.images) || {};

    for (const id of ids) {
      const slug = idToSlug[id];
      const url = images[id];
      let result;
      if (!url) {
        result = { ok: false, reason: "render-failed" };
      } else {
        try {
          const buf = await rest.fetchBinary(url);
          result = normalizeGraphicSvg(buf.toString("utf8"));
        } catch (_e) {
          result = { ok: false, reason: "render-failed" };
        }
      }
      if (result.ok) {
        cleanArtwork[slug] = { viewBox: result.viewBox, body: result.body };
      } else {
        degraded.push({ slug, reason: result.reason });
      }
    }
  }

  // Stable, sorted output for idempotent diffs.
  const sortedSlugs = Object.keys(cleanArtwork).sort();
  const sortedArtwork = {};
  for (const slug of sortedSlugs) sortedArtwork[slug] = cleanArtwork[slug];
  degraded.sort((a, b) => a.slug.localeCompare(b.slug));

  // Operational visibility: one concise line so a run is never opaque.
  const reasonHist = {};
  for (const d of degraded)
    reasonHist[d.reason] = (reasonHist[d.reason] || 0) + 1;
  console.log(
    "[graphics] exported=" +
      sortedSlugs.length +
      " degraded=" +
      degraded.length +
      (degraded.length ? " by-reason=" + JSON.stringify(reasonHist) : ""),
  );

  const auto = {
    _schema_version: 1,
    _regen: {
      source: "figma",
      fileKey: fileKey,
      instructions:
        "Auto-generated by scripts/graphics/export-graphics-svg.js (color-preserving artwork tier). Do not hand-edit.",
    },
    graphics: sortedArtwork,
  };

  // Only (over)write the auto file when there's at least one clean artwork
  // entry, and only when `write` is set: an empty set on a transient
  // all-degraded run must never clobber a prior good export, and a caller
  // that opted out of writing (tests) must never touch disk at all. The
  // degraded worklist is written whenever `write` is set, even if empty, so a
  // fixed prior worklist doesn't linger stale.
  let wrote = false;
  if (write) {
    if (sortedSlugs.length > 0) {
      wrote =
        writeIfChangedStr(
          AUTO_OUT_PATH,
          JSON.stringify(auto, null, 2) + "\n",
        ) || wrote;
    }
    wrote =
      writeIfChangedStr(
        DEGRADED_OUT_PATH,
        JSON.stringify({ _meta: { auto_generated: true }, degraded }, null, 2) +
          "\n",
      ) || wrote;
  }

  return {
    exported: sortedSlugs,
    degraded,
    skipped: 0,
    wrote,
  };
}

// Byte-gated write, returns true only when the file content actually changed.
function writeIfChangedStr(p, str) {
  if (fs.existsSync(p) && fs.readFileSync(p, "utf8") === str) return false;
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, str);
  return true;
}

module.exports = { run, SLICE1_ARTWORK };
