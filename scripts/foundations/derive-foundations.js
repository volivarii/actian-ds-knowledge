// CLI
// ───────────────────────────────────────────────────────────────────────────

function parseArgs(argv) {
  var args = {};
  for (var i = 2; i < argv.length; i++) {
    var a = argv[i];
    if (a === "--check") args.check = true;
    else if (a === "--md") args.md = argv[++i];
    else if (a === "--out") args.out = argv[++i];
    else if (a === "--manifest") args.manifest = argv[++i];
    else if (a === "--no-manifest") args.noManifest = true;
    else if (a === "--no-prune") args.noPrune = true;
    // Legacy compatibility — accept --map and ignore (PR α.5 removes the map)
    else if (a === "--map") {
      args._legacyMap = argv[++i];
    }
  }
  return args;
}

function defaultPaths() {
  var repoRoot = path.resolve(__dirname, "..", "..");
  return {
    md: path.join(repoRoot, "foundations", "src", "foundations.md"),
    out: path.join(repoRoot, "foundations", "dist"),
    manifest: path.join(repoRoot, "paths-manifest.json"),
    repoRoot: repoRoot,
  };
}

function runCli(argv) {
  var args = parseArgs(argv);
  var defaults = defaultPaths();
  var mdPath = args.md || defaults.md;
  var outDir = args.out || defaults.out;
  var manifestPath = args.manifest || defaults.manifest;

  if (args._legacyMap) {
    console.warn(
      "[derive-foundations] --map is deprecated (schema-less derive uses MD structure directly); ignoring '" +
        args._legacyMap +
        "'.",
    );
  }

  if (!fs.existsSync(mdPath)) {
    console.error(
      "[derive-foundations] source MD not found: " +
        mdPath +
        "\nCheck the path — is it really at foundations/src/foundations.md?",
    );
    return 2;
  }

  var md = fs.readFileSync(mdPath, "utf-8");
  var logger = {
    warn: function (m) {
      console.warn("[derive-foundations] " + m);
    },
  };

  var result;
  try {
    result = deriveFromMarkdown(md, { logger: logger });
  } catch (err) {
    console.error("[derive-foundations] failed to parse MD: " + err.message);
    console.error(
      "  Hint: check for malformed tables (missing column header, missing pipe), unclosed code fences, or H2/H3 nesting issues near the line in question.",
    );
    return 3;
  }
  var output = result.output;
  var meta = result.meta;

  // Compute repo-root-relative source path for _meta.source
  var sourceRel = path.relative(defaults.repoRoot, mdPath).replace(/\\/g, "/");

  if (args.check) {
    var drifts = [];
    var files = Object.keys(output);
    for (var i = 0; i < files.length; i++) {
      var name = files[i];
      var expected =
        JSON.stringify(addMetaHeader(output[name], sourceRel), null, 2) + "\n";
      var dest = path.join(outDir, name);
      var actual = fs.existsSync(dest) ? fs.readFileSync(dest, "utf-8") : "";
      if (actual !== expected) drifts.push(name);
    }
    // Stale files (in dist but not in current MD)
    var existing = fs.existsSync(outDir) ? fs.readdirSync(outDir) : [];
    var stale = [];
    for (var s = 0; s < existing.length; s++) {
      var fname = existing[s];
      if (!/\.json$/.test(fname)) continue;
      if (output[fname]) continue;
      stale.push(fname);
    }
    if (drifts.length === 0 && stale.length === 0) {
      console.log("[derive-foundations] no drift");
      return 0;
    }
    if (drifts.length)
      console.error(
        "[derive-foundations] drift detected in: " + drifts.join(", "),
      );
    if (stale.length)
      console.error(
        "[derive-foundations] stale files (would be removed): " +
          stale.join(", "),
      );
    console.error("Run `npm run derive:foundations` to regenerate.");
    return 1;
  }

  var wr = writeOutputs(output, outDir, {
    sourceRel: sourceRel,
    skipPrune: args.noPrune,
  });

  if (!args.noManifest) {
    var manifestResult = updatePathsManifest(
      manifestPath,
      output,
      meta,
      sourceRel,
    );
    console.log(
      "[derive-foundations] manifest: +" +
        manifestResult.added.length +
        " entries, -" +
        manifestResult.dropped.length +
        " entries",
    );
  }

  console.log(
    "[derive-foundations] wrote " +
      wr.written.length +
      " files to " +
      outDir +
      (wr.removed.length ? " (pruned " + wr.removed.length + " stale)" : ""),
  );
  if (wr.removed.length) {
    console.log("[derive-foundations] pruned: " + wr.removed.join(", "));
  }
  return 0;
}

if (require.main === module) {
  process.exit(runCli(process.argv));
}

