"use strict";

// Schema-less foundations derive (PR α.5, v0.4.1+).
//
// Walks the AST of foundations/src/foundations.md and emits one JSON file per
// structural unit (leaf-H3 rule, or H2 if no H3 children). The MD structure
// determines the output structure — no fixed mapping table.
//
// Authors (Design system lead + Content lead) can renumber, rename, or remove
// sections freely; the derive pipeline adapts. The previous parser was hardcoded
// to section numbers (e.g. "2.9 Motion"); a renumber broke it silently. See
// commit history + PR for context.
//
// Special case: a section whose H4 sub-headings include "Duration" + "Easing"
// + "Delay" + "Component Motion Guide" gets the structured motion payload
// (tokens by category + named patterns with phases). Detection is by content
// shape, not section number — Kristina can move Motion from 2.9 to 2.11 and
// the structured emit still works.
//
// `paths-manifest.json` foundations.* entries are auto-regenerated by this
// script based on the actual dist files produced.

var fs = require("fs");
var path = require("path");
var astWalk = require("./foundations-parser/ast-walk.js");
var extractors = require("./foundations-parser/extractors.js");
var statusEmoji = require("./foundations-parser/status-emoji.js");

// ───────────────────────────────────────────────────────────────────────────
// Status emoji application — common helper for token tables
// ───────────────────────────────────────────────────────────────────────────

function applyStatusToRows(rows, sectionLabel, logger) {
  return rows.map(function (row) {
    var copy = {};
    var status = null;
    var keys = Object.keys(row);
    var statusColRaw = null;
    for (var i = 0; i < keys.length; i++) {
      var k = keys[i];
      var v = row[k];
      if (k.toLowerCase() === "status") {
        statusColRaw = v;
        var parsed = statusEmoji.extractStatus.fromValueCell(v);
        status = parsed.status;
        var emojiRecognized =
          statusEmoji.extractStatus(String(v).trim()) !== null ||
          Object.prototype.hasOwnProperty.call(
            statusEmoji.extractStatus.STATUS_MAP,
            String(v).trim(),
          );
        if (parsed.value && parsed.value.length > 0) {
          copy.status_note = parsed.value;
        }
        if (!emojiRecognized) {
          statusColRaw = v;
        } else {
          statusColRaw = null;
        }
        continue;
      }
      copy[k] = v;
    }
    if (status) copy.status = status;
    if (statusColRaw && status === null && !copy.status_note && logger) {
      logger.warn(
        "Section '" +
          sectionLabel +
          "': unrecognized status cell '" +
          statusColRaw +
          "'. " +
          statusEmoji.extractStatus.suggestionHint(),
      );
    }
    return copy;
  });
}

// ───────────────────────────────────────────────────────────────────────────
// Motion payload (special-cased structural emit)
// ───────────────────────────────────────────────────────────────────────────

function isBoldOnlyParagraph(token) {
  if (!token || token.type !== "paragraph" || !Array.isArray(token.tokens))
    return false;
  var significant = token.tokens.filter(function (t) {
    if (t.type === "text") return String(t.text || "").trim().length > 0;
    return true;
  });
  return significant.length === 1 && significant[0].type === "strong";
}

function decodeHtmlEntities(s) {
  return String(s || "")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">");
}

function slugifyPatternName(name) {
  var s = decodeHtmlEntities(name)
    .replace(/^The\s+/i, "")
    .replace(/["“”]/g, "")
    .replace(/\(.*?\)/g, "")
    .replace(/—.*$/, "")
    .trim()
    .toLowerCase();
  s = s.replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  return s;
}

// Canonical pattern slugs (cross-reference IDs consumed by category defaults
// and the future MCP server). Independent of the short object-key slug used
// as the patterns map key.
var CANONICAL_PATTERN_SLUGS = {
  "Drawer (open/close)": "drawer-open-close",
  "Accordion (expand/collapse)": "accordion-expand-collapse",
  "Success Toast": "success-toast",
  'The "Anchor" Motion — Dropdowns, Popovers, and Tooltips': "anchor-motion",
  "Layered Overlays — Modals": "layered-overlays-modals",
  "Skeleton Loading": "skeleton-loading",
  "Staggered Entrance — Lists, Table Rows, Search Cards": "staggered-entrance",
  "State Transitions": "state-transitions",
};

function canonicalSlugForPattern(name) {
  if (CANONICAL_PATTERN_SLUGS[name]) return CANONICAL_PATTERN_SLUGS[name];
  var decoded = decodeHtmlEntities(name)
    .replace(/^The\s+/i, "")
    .replace(/["“”]/g, "")
    .trim()
    .toLowerCase();
  return decoded.replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

function isPatternSubsectionLabel(decodedName) {
  return /^\s*logic\s*&\s*accessibility\s*$/i.test(decodedName);
}

// Detect whether a section's content shape looks like the Motion section:
// H4 sub-headings include Duration / Easing / Delay. (Component Motion Guide
// is optional — its absence means no patterns, just tokens.)
function isMotionShape(contentTokens) {
  var seen = { duration: false, easing: false, delay: false };
  for (var i = 0; i < contentTokens.length; i++) {
    var tok = contentTokens[i];
    if (tok.type === "heading" && tok.depth === 4) {
      var h = String(tok.text || "")
        .toLowerCase()
        .trim();
      if (h === "duration") seen.duration = true;
      else if (h === "easing") seen.easing = true;
      else if (h === "delay") seen.delay = true;
    }
  }
  return seen.duration && seen.easing && seen.delay;
}

function buildMotionPayload(contentTokens, sectionLabel, logger) {
  var payload = { description: null, tokens: {}, patterns: {} };
  var introLines = [];
  var mode = "intro"; // intro | duration | easing | delay | guide
  var currentPatternSlug = null;

  function ensureTokenBucket(key) {
    if (!payload.tokens[key]) payload.tokens[key] = {};
    return payload.tokens[key];
  }

  for (var i = 0; i < contentTokens.length; i++) {
    var tok = contentTokens[i];

    if (tok.type === "heading" && tok.depth === 4) {
      var h = String(tok.text || "")
        .toLowerCase()
        .trim();
      if (h === "duration") mode = "duration";
      else if (h === "easing") mode = "easing";
      else if (h === "delay") mode = "delay";
      else if (h === "component motion guide") {
        mode = "guide";
        currentPatternSlug = null;
      } else {
        currentPatternSlug = null;
      }
      continue;
    }

    if (mode === "intro" && tok.type === "paragraph") {
      var prose = extractors.extractProse(tok);
      if (prose) introLines.push(prose);
      continue;
    }

    if (mode === "duration" || mode === "easing" || mode === "delay") {
      var bucket = ensureTokenBucket(mode);
      if (tok.type === "table") {
        var rows = extractors.extractTable(tok);
        bucket.rows = applyStatusToRows(rows, sectionLabel, logger);
      } else if (tok.type === "paragraph") {
        var p = extractors.extractProse(tok);
        if (p)
          bucket.description = bucket.description
            ? bucket.description + "\n\n" + p
            : p;
      }
      continue;
    }

    if (mode === "guide") {
      if (tok.type === "paragraph") {
        if (isBoldOnlyParagraph(tok)) {
          var rawName = extractors.extractProse(tok).trim();
          var name = decodeHtmlEntities(rawName);
          if (isPatternSubsectionLabel(name) && currentPatternSlug) {
            payload.patterns[currentPatternSlug]._pendingSubsection =
              "logic_and_accessibility";
            continue;
          }
          var slug = slugifyPatternName(rawName);
          if (!slug) {
            logger.warn(
              "Section '" +
                sectionLabel +
                "' pattern paragraph '" +
                name +
                "' produced empty slug; skipping",
            );
            currentPatternSlug = null;
            continue;
          }
          if (payload.patterns[slug]) {
            logger.warn(
              "Section '" +
                sectionLabel +
                "' duplicate pattern slug '" +
                slug +
                "' — keeping first",
            );
            currentPatternSlug = null;
            continue;
          }
          payload.patterns[slug] = {
            slug: canonicalSlugForPattern(name),
            name: name,
            phases: [],
          };
          currentPatternSlug = slug;
          continue;
        }
        var notesText = decodeHtmlEntities(extractors.extractProse(tok));
        if (notesText && currentPatternSlug) {
          var pat = payload.patterns[currentPatternSlug];
          if (!pat.notes) pat.notes = [];
          pat.notes.push(notesText);
        }
        continue;
      }
      if (tok.type === "table" && currentPatternSlug) {
        payload.patterns[currentPatternSlug].phases =
          extractors.extractTable(tok);
        continue;
      }
      if (tok.type === "list" && currentPatternSlug) {
        var listItems = extractors.extractList(tok).map(decodeHtmlEntities);
        var pendingKey =
          payload.patterns[currentPatternSlug]._pendingSubsection ||
          "logic_and_accessibility";
        payload.patterns[currentPatternSlug][pendingKey] = listItems;
        delete payload.patterns[currentPatternSlug]._pendingSubsection;
        continue;
      }
    }
  }

  if (introLines.length) payload.description = introLines.join("\n\n");
  if (!payload.description) delete payload.description;
  if (Object.keys(payload.tokens).length === 0) delete payload.tokens;
  if (Object.keys(payload.patterns).length === 0) delete payload.patterns;

  Object.keys(payload.patterns || {}).forEach(function (slug) {
    if (payload.patterns[slug] && payload.patterns[slug]._pendingSubsection) {
      delete payload.patterns[slug]._pendingSubsection;
    }
  });
  return payload;
}

// ───────────────────────────────────────────────────────────────────────────
// Generic section payload (default emit shape)
// ───────────────────────────────────────────────────────────────────────────

// Heuristic: a paragraph "looks like a malformed table" if it has ≥2 lines,
// each starting with `|` and containing ≥2 pipes — but no separator row of
// dashes. Markdown requires `|---|` between header and data rows; missing it
// makes marked parse the whole block as plain text. We surface this as an
// author-friendly warning rather than silently dropping the data.
function looksLikeMalformedTable(prose) {
  var lines = String(prose)
    .split(/\n/)
    .filter(function (l) {
      return l.trim().length > 0;
    });
  if (lines.length < 2) return false;
  var pipeyLines = 0;
  var hasSeparator = false;
  for (var i = 0; i < lines.length; i++) {
    var ln = lines[i].trim();
    if (/^\|.*\|/.test(ln) && (ln.match(/\|/g) || []).length >= 2) {
      pipeyLines++;
      if (/^\|?\s*[-:]+\s*(\|\s*[-:]+\s*)+\|?\s*$/.test(ln)) {
        hasSeparator = true;
      }
    }
  }
  return pipeyLines >= 2 && !hasSeparator;
}

// Build payload from a flat content slice. Sub-headings (H4+) become group
// markers in the description; tables/lists/code are aggregated. The output
// shape is intentionally flat — consumers query it with the same logic
// regardless of which leaf section it came from.
function buildSectionPayload(contentTokens, sectionLabel, logger) {
  var payload = {
    rows: [],
    lists: [],
    code: [],
    description: null,
    groups: [],
  };
  var descLines = [];
  var currentGroup = null;

  function ensureGroup(name) {
    var g = { name: name, rows: [], lists: [], code: [], description: null };
    payload.groups.push(g);
    return g;
  }

  for (var i = 0; i < contentTokens.length; i++) {
    var token = contentTokens[i];
    if (token.type === "heading" && token.depth >= 4) {
      // H4+ subdivisions become groups inside this section's payload.
      // (Per the leaf-H3 rule, the schema-less walker doesn't emit per-H4
      // files; it lets us aggregate them as named groups.)
      currentGroup = ensureGroup(String(token.text || "").trim());
      continue;
    }
    var target = currentGroup || payload;
    var localDescLines = currentGroup ? null : descLines;
    if (token.type === "table") {
      var rows = extractors.extractTable(token);
      if (rows.length === 0) continue;
      // Detect malformed table early — table with no header is suspicious
      target.rows = target.rows.concat(
        applyStatusToRows(rows, sectionLabel, logger),
      );
    } else if (token.type === "list") {
      target.lists.push(extractors.extractList(token));
    } else if (token.type === "code") {
      var fb = extractors.extractFencedBlock(token);
      if (fb) target.code.push(fb);
    } else if (token.type === "paragraph") {
      var prose = extractors.extractProse(token);
      if (!prose) continue;
      // Detect a paragraph that LOOKS like a malformed table — multiple pipe
      // characters on multiple lines but no `|---|` separator row, so marked
      // parsed it as text instead of a table. Surface this as an author-
      // friendly warning rather than silently dropping the data.
      if (looksLikeMalformedTable(prose) && logger) {
        logger.warn(
          "Section '" +
            sectionLabel +
            "' contains a block that looks like a table but is missing the `|---|` header separator row. " +
            "I parsed it as plain text instead of a table. Add a separator row right under the column headers — for example: `| --- | --- |`.",
        );
      }
      if (currentGroup) {
        currentGroup.description = currentGroup.description
          ? currentGroup.description + "\n\n" + prose
          : prose;
      } else if (localDescLines) {
        localDescLines.push(prose);
      }
    }
  }

  payload.description = descLines.length ? descLines.join("\n\n") : null;

  // Drop empty buckets to keep JSON clean.
  if (payload.rows.length === 0) delete payload.rows;
  if (payload.lists.length === 0) delete payload.lists;
  if (payload.code.length === 0) delete payload.code;
  if (payload.description === null) delete payload.description;
  if (payload.groups.length === 0) {
    delete payload.groups;
  } else {
    // Clean empty buckets per group too
    payload.groups = payload.groups.map(function (g) {
      var clean = { name: g.name };
      if (g.description) clean.description = g.description;
      if (g.rows.length) clean.rows = g.rows;
      if (g.lists.length) clean.lists = g.lists;
      if (g.code.length) clean.code = g.code;
      return clean;
    });
  }

  return payload;
}

// ───────────────────────────────────────────────────────────────────────────
// Top-level derive
// ───────────────────────────────────────────────────────────────────────────

// Sections whose H2 slug should be skipped entirely (out-of-scope content).
// These are intentionally hand-listed — they represent process docs / pointers
// rather than design-system data. Authors can override by passing --no-skip
// (future flag) or by editing this list. We keep it SHORT — schema-less means
// most sections should pass through unfiltered.
var SKIP_H2_SLUGS = {
  "handoff-protocol": true,
  "related-guidelines": true,
};

function buildSectionRecord(section, logger) {
  var label = section.heading || section.slug;
  var content = section.content;

  // Filter out sub-headings + nested content for H4-handled cases below.
  // The motion payload handles its own H4 walk; the generic payload also
  // handles H4 as group markers, so we pass content through as-is.

  if (isMotionShape(content)) {
    return {
      payload: buildMotionPayload(content, label, logger),
      isMotion: true,
    };
  }
  return {
    payload: buildSectionPayload(content, label, logger),
    isMotion: false,
  };
}

function deriveFromMarkdown(mdSource, opts) {
  opts = opts || {};
  var logger = opts.logger || { warn: function () {} };
  var skipMap = opts.skipH2Slugs || SKIP_H2_SLUGS;

  var tokens = astWalk.parseMarkdown(mdSource);
  var sections = astWalk.findEmitSections(tokens, { skipH2Slugs: skipMap });
  var output = {};
  var meta = []; // ordered metadata for paths-manifest gen

  for (var i = 0; i < sections.length; i++) {
    var section = sections[i];
    var record = buildSectionRecord(section, logger);
    var file = section.slug + ".json";

    if (output[file]) {
      logger.warn(
        "Slug collision on '" +
          section.slug +
          "' — second occurrence (heading: " +
          section.heading +
          ") will overwrite first.",
      );
    }
    output[file] = record.payload;
    meta.push({
      file: file,
      slug: section.slug,
      heading: section.heading,
      kind: section.kind,
      depth: section.depth,
      isMotion: record.isMotion,
    });
  }

  return { output: output, meta: meta };
}

function addMetaHeader(payload, sourceFileRel) {
  var meta = {
    auto_generated: true,
    source: sourceFileRel || "foundations/src/foundations.md",
    do_not_edit: "Edit the source MD; CI regenerates this file.",
  };
  var out = { _schema_version: 1, _meta: meta };
  var keys = Object.keys(payload);
  for (var i = 0; i < keys.length; i++) {
    out[keys[i]] = payload[keys[i]];
  }
  return out;
}

function writeOutputs(output, outputDir, opts) {
  opts = opts || {};
  if (!fs.existsSync(outputDir)) fs.mkdirSync(outputDir, { recursive: true });
  var written = [];
  var files = Object.keys(output);
  var sourceRel = opts.sourceRel || "foundations/src/foundations.md";

  for (var i = 0; i < files.length; i++) {
    var name = files[i];
    var payload = addMetaHeader(output[name], sourceRel);
    var dest = path.join(outputDir, name);
    fs.writeFileSync(dest, JSON.stringify(payload, null, 2) + "\n");
    written.push(name);
  }

  // Idempotent: clean up dist files that no longer have a corresponding
  // section in the source MD. We only touch JSON files in outputDir — never
  // README.md or other hand-maintained siblings.
  var removed = [];
  if (!opts.skipPrune) {
    var existing = fs.readdirSync(outputDir);
    for (var j = 0; j < existing.length; j++) {
      var fname = existing[j];
      if (!/\.json$/.test(fname)) continue;
      if (output[fname]) continue;
      // Defensive: verify the file we're about to delete is actually one we
      // own (has the _meta.auto_generated marker). If a hand-curated JSON
      // somehow landed in dist/, we leave it alone.
      var fullPath = path.join(outputDir, fname);
      try {
        var contents = JSON.parse(fs.readFileSync(fullPath, "utf-8"));
        if (
          contents &&
          contents._meta &&
          contents._meta.auto_generated === true
        ) {
          fs.unlinkSync(fullPath);
          removed.push(fname);
        }
      } catch (_e) {
        // Malformed JSON — leave it for a human to deal with
      }
    }
  }

  return { written: written, removed: removed };
}

// ───────────────────────────────────────────────────────────────────────────
// paths-manifest.json auto-generation (foundations.* entries only)
// ───────────────────────────────────────────────────────────────────────────

// Marker comment authors should not edit; defines the auto-managed block.
var MANIFEST_FOUNDATIONS_NOTE =
  "foundations.* entries are auto-regenerated by scripts/foundations/derive-foundations.js. Do not hand-edit.";

function updatePathsManifest(manifestPath, output, meta, sourceRel, opts) {
  opts = opts || {};
  var manifest = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
  if (!manifest.paths) manifest.paths = {};

  // 1. Drop any existing foundations.* path entries EXCEPT the human-maintained
  //    source pointers (foundations.md, foundations.authoring). Those are
  //    pointers to authored content, not auto-generated derivatives.
  var preservedKeys = { "foundations.md": true, "foundations.authoring": true };
  var dropped = [];
  Object.keys(manifest.paths).forEach(function (k) {
    if (k.indexOf("foundations.") !== 0) return;
    if (preservedKeys[k]) return;
    dropped.push(k);
    delete manifest.paths[k];
  });

  // 2. Insert one entry per dist file, keyed by `foundations.<slug>`. The slug
  //    is the same one used in the filename (no transformation).
  var added = [];
  for (var i = 0; i < meta.length; i++) {
    var m = meta[i];
    var slug = m.slug;
    var key = "foundations." + slug;
    var distRel = "foundations/dist/" + m.file;
    var description =
      "Auto-derived from foundations.md — section '" + m.heading + "'";
    if (m.isMotion) {
      description += " (structured motion payload: tokens + patterns)";
    }
    manifest.paths[key] = {
      path: distRel,
      type: "json",
      origin: "ci",
      generator: "scripts/foundations/derive-foundations.js",
      description: description,
    };
    added.push(key);
  }

  // 3. Marker note (read by future contributors so they don't hand-edit).
  manifest._notes = manifest._notes || {};
  manifest._notes.foundations_auto = MANIFEST_FOUNDATIONS_NOTE;

  if (!opts.dryRun) {
    fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  }
  return { added: added, dropped: dropped, manifest: manifest };
}

