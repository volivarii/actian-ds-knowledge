#!/usr/bin/env node
"use strict";

// Federation Phase 1.5 — pure transform from tokens.json (DTCG) to
// tokens/token-reference.md. Reads the DTCG-shaped JSON, walks the
// type/value tree, emits a flat markdown table grouped by category
// (color, spacing, typography, etc.). No Figma API calls.

var fs = require("fs");
var path = require("path");

var REPO_ROOT = path.resolve(__dirname, "..");
var TOKENS_PATH = path.join(REPO_ROOT, "tokens", "tokens.json");
var OUT_PATH = path.join(REPO_ROOT, "tokens", "token-reference.md");

// Allow callers to override paths via argv: --tokens-path=... --out-path=...
// Used by dry-run tests and CI tooling. Defaults preserve existing behaviour.
function parseArgPaths(argv) {
  var tokensPath = TOKENS_PATH;
  var outPath = OUT_PATH;
  for (var arg of argv) {
    var m;
    if ((m = arg.match(/^--tokens-path=(.+)$/))) tokensPath = m[1];
    if ((m = arg.match(/^--out-path=(.+)$/))) outPath = m[1];
  }
  return { tokensPath, outPath };
}

function loadTokens(tokensPath) {
  return JSON.parse(fs.readFileSync(tokensPath || TOKENS_PATH, "utf8"));
}

// Prefer the already-resolved hex from com.actian.themes.actian; falls back to
// $value for non-color tokens (numerics, spacing) that have no themes extension.
// This makes the renderer alias-tolerant: correct both pre-flip ($value == hex)
// and post-flip ($value == {alias}).
function resolvedHex(leaf) {
  var ext = leaf && leaf.$extensions;
  var themes = ext && ext["com.actian.themes"];
  var actian = themes && themes.actian;
  return actian != null ? actian : leaf.$value;
}

// Walk the DTCG tree, collecting flat { path, type, value } entries.
// DTCG marker: an entry is a token if it has `$value` + `$type`.
function walk(obj, prefix, out) {
  if (!obj || typeof obj !== "object") return;
  if (obj.$value !== undefined && obj.$type !== undefined) {
    out.push({
      name: prefix.join("."),
      cssVar: "--zen-" + prefix.join("-"),
      type: obj.$type,
      value: resolvedHex(obj),
      description: obj.$description || "",
    });
    return;
  }
  for (var key of Object.keys(obj)) {
    if (key.startsWith("$")) continue;
    walk(obj[key], prefix.concat(key), out);
  }
}

function groupByType(entries) {
  var groups = {};
  for (var e of entries) {
    if (!groups[e.type]) groups[e.type] = [];
    groups[e.type].push(e);
  }
  return groups;
}

function renderGroup(type, entries) {
  var lines = [
    "## " + type.charAt(0).toUpperCase() + type.slice(1) + " Tokens",
    "",
  ];
  lines.push("| Token | CSS Variable | Value |");
  lines.push("|-------|--------------|-------|");
  for (var e of entries) {
    var val = typeof e.value === "string" ? e.value : JSON.stringify(e.value);
    lines.push("| `" + e.name + "` | `" + e.cssVar + "` | `" + val + "` |");
  }
  lines.push("");
  return lines.join("\n");
}

function renderMarkdown(tokens, sourcePath) {
  var entries = [];
  walk(tokens, [], entries);
  var grouped = groupByType(entries);

  // Default source path is tokens/tokens.json; callers may override for candidate/dry-run
  var source = sourcePath || "tokens/tokens.json";

  var out = [
    "<!-- AUTO-GENERATED — DO NOT EDIT. Source: " + source + " -->",
    "<!-- Generator: scripts/render-token-reference.js -->",
    "",
    "# Token Reference — Actian Design System",
    "",
    "Auto-generated by `scripts/render-token-reference.js` from `" +
      source +
      "` (DTCG W3C draft format).",
    "",
    "Total tokens: " +
      entries.length +
      ". Groups: " +
      Object.keys(grouped).length +
      ".",
    "",
  ];

  var orderedTypes = Object.keys(grouped).sort();
  for (var t of orderedTypes) {
    out.push(renderGroup(t, grouped[t]));
  }

  return {
    markdown: out.join("\n"),
    entryCount: entries.length,
  };
}

function main() {
  var { tokensPath, outPath } = parseArgPaths(process.argv.slice(2));
  var tokens = loadTokens(tokensPath);
  var { markdown, entryCount } = renderMarkdown(tokens);

  // Honour out-path override (default: TOKENS_PATH → OUT_PATH, but caller may
  // pass --out-path= to dry-run without touching the live token-reference.md).
  var dest = outPath;
  fs.writeFileSync(dest, markdown);
  console.log(
    "[render-token-reference] wrote " + entryCount + " tokens to " + dest,
  );
}

if (require.main === module) main();
module.exports = {
  walk: walk,
  groupByType: groupByType,
  renderGroup: renderGroup,
  renderMarkdown: renderMarkdown,
  TOKENS_PATH: TOKENS_PATH,
  OUT_PATH: OUT_PATH,
};
