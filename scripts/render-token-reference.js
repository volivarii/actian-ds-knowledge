#!/usr/bin/env node
"use strict";

// Federation Phase 1.5 — pure transform from tokens.json (DTCG) to
// tokens/token-reference.md. Reads the DTCG-shaped JSON, walks the
// type/value tree, emits a flat markdown table grouped by category
// (color, spacing, typography, etc.). No Figma API calls.

var fs = require("fs");
var path = require("path");

var REPO_ROOT = path.resolve(__dirname, "..");
var TOKENS_PATH = path.join(REPO_ROOT, "tokens", "tokens.json");
var OUT_PATH = path.join(REPO_ROOT, "tokens", "token-reference.md");

function loadTokens() {
  return JSON.parse(fs.readFileSync(TOKENS_PATH, "utf8"));
}

// Walk the DTCG tree, collecting flat { path, type, value } entries.
// DTCG marker: an entry is a token if it has `$value` + `$type`.
function walk(obj, prefix, out) {
  if (!obj || typeof obj !== "object") return;
  if (obj.$value !== undefined && obj.$type !== undefined) {
    out.push({
      name: prefix.join("."),
      cssVar: "--zen-" + prefix.join("-"),
      type: obj.$type,
      value: obj.$value,
      description: obj.$description || "",
    });
    return;
  }
  for (var key of Object.keys(obj)) {
    if (key.startsWith("$")) continue;
    walk(obj[key], prefix.concat(key), out);
  }
}

function groupByType(entries) {
  var groups = {};
  for (var e of entries) {
    if (!groups[e.type]) groups[e.type] = [];
    groups[e.type].push(e);
  }
  return groups;
}

function renderGroup(type, entries) {
  var lines = [
    "## " + type.charAt(0).toUpperCase() + type.slice(1) + " Tokens",
    "",
  ];
  lines.push("| Token | CSS Variable | Value |");
  lines.push("|-------|--------------|-------|");
  for (var e of entries) {
    var val = typeof e.value === "string" ? e.value : JSON.stringify(e.value);
    lines.push("| `" + e.name + "` | `" + e.cssVar + "` | `" + val + "` |");
  }
  lines.push("");
  return lines.join("\n");
}

function main() {
  var tokens = loadTokens();
  var entries = [];
  walk(tokens, [], entries);
  var grouped = groupByType(entries);

  var out = [
    "<!-- AUTO-GENERATED — DO NOT EDIT. Source: tokens/tokens.json -->",
    "<!-- Generator: scripts/render-token-reference.js -->",
    "",
    "# Token Reference — Actian Design System",
    "",
    "Auto-generated by `scripts/render-token-reference.js` from `tokens/tokens.json` (DTCG W3C draft format).",
    "",
    "Total tokens: " +
      entries.length +
      ". Groups: " +
      Object.keys(grouped).length +
      ".",
    "",
  ];

  var orderedTypes = Object.keys(grouped).sort();
  for (var t of orderedTypes) {
    out.push(renderGroup(t, grouped[t]));
  }

  fs.writeFileSync(OUT_PATH, out.join("\n"));
  console.log(
    "[render-token-reference] wrote " +
      entries.length +
      " tokens to " +
      OUT_PATH,
  );
}

if (require.main === module) main();
module.exports = {
  walk: walk,
  groupByType: groupByType,
  renderGroup: renderGroup,
};
